"""Synthetic case service: generate -> seal truth -> create case -> ingest public files via the SAME upload pipeline."""
from __future__ import annotations

from sqlalchemy.orm import Session

from app.graph.rules import rebuild_derived
from app.models import Case, SyntheticScenario, User
from app.services import audit
from app.services.ingestion import IngestOutcome, ingest_upload
from app.synthetic import sealed_store
from app.synthetic.artifacts import build_bundle, truth_to_dict
from app.synthetic.generator import GENERATOR_VERSION, SCENARIO_VERSION, Generator


def generate_case(db: Session, user: User, *, scenario_type: str, difficulty: str, size: str, seed: int,
                  title: str | None = None, ingest: bool = True, safeguards: bool = True, infra: bool = True) -> tuple[Case, SyntheticScenario, list[IngestOutcome], dict]:
    gen = Generator(scenario_type, difficulty, size, seed)
    files, truth, manifest = build_bundle(gen)
    ref = sealed_store.seal(truth_to_dict(truth), scenario_type, difficulty, size, seed, SCENARIO_VERSION)
    case = Case(title=title or f"[SYNTHETIC] {scenario_type.replace('_', ' ')} / {difficulty} / seed {seed}",
                internal_ref=f"SYN-{seed}", summary="Synthetic demonstration case generated by the PS05-X case factory. No real persons, accounts or domains.",
                is_synthetic=True, created_by=user.id)
    db.add(case)
    db.flush()
    scen = SyntheticScenario(case_id=case.id, scenario_type=scenario_type, difficulty=difficulty, size=size, seed=seed,
                             scenario_version=SCENARIO_VERSION, generator_version=GENERATOR_VERSION, public_manifest=manifest, sealed_truth_ref=ref)
    db.add(scen)
    db.flush()
    case.synthetic_scenario_id = scen.id
    audit.record(db, "synthetic.generated", actor_id=user.id, case_id=case.id, target_type="synthetic_scenario", target_id=scen.id,
                 detail={"scenario_type": scenario_type, "difficulty": difficulty, "size": size, "seed": seed})
    outcomes: list[IngestOutcome] = []
    if ingest:
        for name in sorted(files):
            if name == "case_manifest.json":
                continue  # metadata, not evidence
            outcomes.append(ingest_upload(db, case, user, name, files[name], is_synthetic=True))
        rebuild_derived(db, case, safeguards=safeguards, infra=infra)
    db.flush()
    return case, scen, outcomes, manifest
