"""Create or update the PS05-X API on Render through the public REST API.

Idempotent: re-running finds existing resources by name. Secrets are generated once and written to
DEPLOY_SECRETS.local.md (gitignored); they are never printed to stdout.

Auth: RENDER_API_KEY env var, else the key stored by `render login` in ~/.render/cli.yaml.
Usage: python scripts/render_deploy.py [--repo URL] [--branch main] [--region singapore] [--no-wait]
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import sys
import time
from pathlib import Path

import httpx

API = "https://api.render.com/v1"
ROOT = Path(__file__).resolve().parents[1]
SECRETS_FILE = ROOT / "DEPLOY_SECRETS.local.md"


def api_key() -> str:
    k = os.environ.get("RENDER_API_KEY")
    if k:
        return k
    cfg = Path.home() / ".render" / "cli.yaml"
    for line in cfg.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("key:"):
            return s.split(":", 1)[1].strip().strip('"')
    sys.exit("No Render API key: set RENDER_API_KEY or run `render login`.")


class Render:
    def __init__(self, key: str):
        self.c = httpx.Client(base_url=API, headers={"Authorization": f"Bearer {key}", "Accept": "application/json"}, timeout=60)

    def get(self, path, **params):
        r = self.c.get(path, params=params)
        r.raise_for_status()
        return r.json()

    def post(self, path, body):
        r = self.c.post(path, json=body)
        if r.status_code >= 400:
            sys.exit(f"Render API error {r.status_code} on POST {path}: {r.text[:800]}")
        return r.json()

    def put(self, path, body):
        r = self.c.put(path, json=body)
        if r.status_code >= 400:
            sys.exit(f"Render API error {r.status_code} on PUT {path}: {r.text[:800]}")
        return r.json()


def load_or_create_secrets() -> dict:
    if SECRETS_FILE.exists():
        data = {}
        for line in SECRETS_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                data[k.strip()] = v.strip()
        if all(k in data for k in ("JWT_SECRET", "DEMO_ANALYST_PASSWORD", "DEMO_SUPERVISOR_PASSWORD", "DEMO_ADMIN_PASSWORD")):
            return data
    data = {"JWT_SECRET": secrets.token_urlsafe(48), "DEMO_ANALYST_PASSWORD": "Analyst-" + secrets.token_urlsafe(9),
            "DEMO_SUPERVISOR_PASSWORD": "Supervisor-" + secrets.token_urlsafe(9), "DEMO_ADMIN_PASSWORD": "Admin-" + secrets.token_urlsafe(9)}
    SECRETS_FILE.write_text("# LOCAL ONLY - gitignored. Production demo credentials and JWT secret generated by scripts/render_deploy.py\n"
                            "# Accounts: analyst@demo.local, supervisor@demo.local, admin@demo.local\n" + "".join(f"{k}={v}\n" for k, v in data.items()), encoding="utf-8")
    return data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default="https://github.com/RAJARYANSINGH0059/RPH")
    ap.add_argument("--branch", default="main")
    ap.add_argument("--region", default="singapore")
    ap.add_argument("--db-name", default="ps05x-db")
    ap.add_argument("--service-name", default="ps05x-api")
    ap.add_argument("--no-wait", action="store_true")
    args = ap.parse_args()
    rd = Render(api_key())
    owners = rd.get("/owners", limit=20)
    owner = next((o["owner"] for o in owners if o["owner"]["type"] == "team"), owners[0]["owner"])
    oid = owner["id"]
    print(f"owner: {owner['name']} ({oid})")

    # ---- PostgreSQL
    existing = [p["postgres"] for p in rd.get("/postgres", ownerId=oid, name=args.db_name, limit=20)]
    if existing:
        pg = existing[0]
        print(f"postgres exists: {pg['id']} status={pg.get('status')}")
    else:
        pg = rd.post("/postgres", {"name": args.db_name, "ownerId": oid, "plan": "free", "region": args.region, "version": "16",
                                   "databaseName": "ps05x", "databaseUser": "ps05x"})
        print(f"postgres created: {pg['id']}")
    for _ in range(60):
        pg = rd.get(f"/postgres/{pg['id']}")
        if pg.get("status") == "available":
            break
        print(f"  waiting for postgres ({pg.get('status')})…")
        time.sleep(10)
    else:
        sys.exit("postgres did not become available in time")
    conn = rd.get(f"/postgres/{pg['id']}/connection-info")
    internal_url = conn["internalConnectionString"]

    # ---- env vars
    sec = load_or_create_secrets()
    env = {
        "PYTHON_VERSION": "3.12.7", "APP_ENV": "production", "DATABASE_URL": internal_url, "JWT_SECRET": sec["JWT_SECRET"],
        "CORS_ORIGINS": "http://localhost:3000", "CORS_ORIGIN_REGEX": r"^https://[a-z0-9-]+\.vercel\.app$",
        "STORAGE_DIR": "/opt/render/project/src/apps/api/data", "BENCHMARK_STORE_DIR": "/opt/render/project/src/apps/api/data/sealed",
        "DEMO_ANALYST_PASSWORD": sec["DEMO_ANALYST_PASSWORD"], "DEMO_SUPERVISOR_PASSWORD": sec["DEMO_SUPERVISOR_PASSWORD"],
        "DEMO_ADMIN_PASSWORD": sec["DEMO_ADMIN_PASSWORD"], "ENABLE_RDAP": "false", "ENABLE_DNS": "false",
    }
    env_vars = [{"key": k, "value": v} for k, v in env.items()]

    # ---- web service
    services = [s["service"] for s in rd.get("/services", ownerId=oid, name=args.service_name, limit=20)]
    start_cmd = "alembic upgrade head && uvicorn app.main:app --host 0.0.0.0 --port $PORT"
    if services:
        svc = services[0]
        print(f"service exists: {svc['id']} -> updating env vars and triggering deploy")
        rd.put(f"/services/{svc['id']}/env-vars", env_vars)
        dep = rd.post(f"/services/{svc['id']}/deploys", {"clearCache": "do_not_clear"})
        deploy_id = dep["id"]
    else:
        body = {"type": "web_service", "name": args.service_name, "ownerId": oid, "repo": args.repo, "branch": args.branch, "rootDir": "apps/api",
                "autoDeploy": "yes", "envVars": env_vars,
                "serviceDetails": {"runtime": "python", "plan": "free", "region": args.region, "healthCheckPath": "/api/health/live",
                                   "envSpecificDetails": {"buildCommand": "pip install -r requirements.txt", "startCommand": start_cmd}}}
        res = rd.post("/services", body)
        svc, deploy_id = res["service"], res.get("deployId")
        print(f"service created: {svc['id']}")
    url = svc.get("serviceDetails", {}).get("url") or f"https://{args.service_name}.onrender.com"
    print(f"service url: {url}")
    print(f"dashboard: {svc.get('dashboardUrl', '')}")
    if args.no_wait:
        return
    # ---- wait for deploy
    for _ in range(90):
        deps = rd.get(f"/services/{svc['id']}/deploys", limit=1)
        d = deps[0]["deploy"] if deps else {}
        st = d.get("status")
        print(f"  deploy {d.get('id', deploy_id)}: {st}")
        if st in {"live"}:
            break
        if st in {"build_failed", "update_failed", "canceled", "deactivated", "pre_deploy_failed"}:
            sys.exit(f"deploy ended with status {st}; check logs: render logs --resources {svc['id']}")
        time.sleep(15)
    # ---- health
    for path in ("/api/health/live", "/api/health/ready"):
        try:
            r = httpx.get(url + path, timeout=30)
            print(f"{path}: {r.status_code} {r.text[:160]}")
        except Exception as exc:
            print(f"{path}: error {type(exc).__name__}")
    print(json.dumps({"service_id": svc["id"], "url": url, "postgres_id": pg["id"]}))


if __name__ == "__main__":
    main()
